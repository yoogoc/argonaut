// Generates TypeScript types and a pruned JSON Schema for the Argo API from the schema that ships
// with the Argo Go module the server is built against, so the UI's types can never drift from the
// server's Argo version. Run after bumping argo-workflows in server/go.mod.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const serverDir = path.resolve(here, "../../server");
const outDir = path.resolve(here, "../src/api/gen");

const argoVersion = execFileSync("go", ["list", "-m", "-f", "{{.Version}}", "github.com/argoproj/argo-workflows/v4"], {
  cwd: serverDir,
  encoding: "utf8",
}).trim();
const modCache = execFileSync("go", ["env", "GOMODCACHE"], { encoding: "utf8" }).trim();
const schemaPath = path.join(modCache, `github.com/argoproj/argo-workflows/v4@${argoVersion}/api/jsonschema/schema.json`);
const full = JSON.parse(readFileSync(schemaPath, "utf8"));
const defs = full.definitions;

const ARGO = "io.argoproj.workflow.v1alpha1.";
const roots = Object.keys(defs).filter((k) => k.startsWith(ARGO));

// Keep only what Argo's own types reach; the upstream schema also carries Argo Events.
const keep = new Set();
const visit = (key) => {
  if (keep.has(key) || !defs[key]) return;
  keep.add(key);
  JSON.stringify(defs[key], (k, v) => {
    if (k === "$ref" && typeof v === "string") visit(v.replace("#/definitions/", ""));
    return v;
  });
};
roots.forEach(visit);

const shortName = (key) => {
  const last = key.split(".").pop();
  if (key.startsWith(ARGO)) return last;
  const clash = [...keep].some((k) => k !== key && k.startsWith(ARGO) && k.endsWith("." + last));
  return clash ? `K8s${last}` : last;
};

const pruned = {};
for (const key of [...keep].sort()) {
  const def = structuredClone(defs[key]);
  // Kubernetes encodes these as strings or numbers on the wire; their schema says "string".
  if (key.endsWith("resource.Quantity")) Object.assign(def, { type: "string", tsType: "string" });
  if (key.endsWith("intstr.IntOrString")) Object.assign(def, { tsType: "string | number" });
  def.title = shortName(key);
  pruned[key] = def;
}

// A "$ref" with sibling keywords (usually a field description) makes json-schema-to-typescript mint
// a numbered copy of the referenced type for every such field. The types keep the descriptions of
// the definitions themselves; the per-field copies only cost readability.
const stripRefSiblings = (node) => {
  if (Array.isArray(node)) return node.map(stripRefSiblings);
  if (!node || typeof node !== "object") return node;
  if (typeof node.$ref === "string") return { $ref: node.$ref };
  return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, stripRefSiblings(v)]));
};
const typed = {};
for (const [key, def] of Object.entries(pruned)) {
  typed[key] = stripRefSiblings(def);
}

const schema = {
  $schema: full.$schema,
  definitions: pruned,
  oneOf: full.oneOf,
};
writeFileSync(path.join(outDir, "argo-schema.json"), JSON.stringify(schema));

const ts = await compile({ title: "ArgoRoot", definitions: typed, oneOf: full.oneOf }, "ArgoRoot", {
  additionalProperties: false,
  bannerComment: `/* Generated by scripts/gen-argo-types.mjs from argo-workflows ${argoVersion}. Do not edit. */`,
  unreachableDefinitions: true,
  format: true,
  strictIndexSignatures: false,
});
writeFileSync(path.join(outDir, "argo.gen.ts"), ts);
writeFileSync(path.join(outDir, "argo-version.ts"), `export const ARGO_VERSION = "${argoVersion}";\n`);
console.log(`argo ${argoVersion}: ${keep.size} definitions`);
