// Generates TypeScript types for argonaut's own API messages from server/api/v1/*.proto, so the UI's
// DTOs cannot drift from the contract. Run after changing a proto (CI checks the output is current).
//
// The server encodes replies with encoding/json over the protoc-gen-go structs (DESIGN §2.2), so the
// JSON shape follows those structs: field names as written in the proto, int64 as a JSON number, and
// every field optional because each carries `omitempty`. Argo objects embedded in replies keep the
// UI's own Argo types (api/types.ts).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const protoDir = path.resolve(here, "../../server/api/v1");
const outFile = path.resolve(here, "../src/api/gen/api.gen.ts");

const ARGO = "github.com.argoproj.argo_workflows.v4.pkg.apis.workflow.v1alpha1.";
const argoTypes = {
  Workflow: "Workflow",
  WorkflowTemplate: "WorkflowTemplate",
  ClusterWorkflowTemplate: "WorkflowTemplate",
  CronWorkflow: "CronWorkflow",
  WorkflowList: "List<Workflow>",
  WorkflowTemplateList: "List<WorkflowTemplate>",
  ClusterWorkflowTemplateList: "List<WorkflowTemplate>",
  CronWorkflowList: "List<CronWorkflow>",
};
const scalars = { string: "string", bool: "boolean", int32: "number", int64: "number", uint32: "number", uint64: "number", double: "number", float: "number", bytes: "string" };

/** Comment lines directly above `index` in `lines`, as JSDoc text. */
function docAbove(lines, index) {
  const out = [];
  for (let i = index - 1; i >= 0 && /^\s*\/\//.test(lines[i]); i--) out.unshift(lines[i].replace(/^\s*\/\/\s?/, ""));
  return out.join(" ").trim();
}

const messages = new Map();
const usedArgo = new Set();
const files = readdirSync(protoDir)
  .filter((f) => f.endsWith(".proto"))
  .sort();

for (const file of files) {
  const lines = readFileSync(path.join(protoDir, file), "utf8").split("\n");
  for (let i = 0; i < lines.length; i++) {
    const start = lines[i].match(/^message (\w+) \{(\})?/);
    if (!start) continue;
    const name = start[1];
    const fields = [];
    const doc = docAbove(lines, i);
    if (!start[2]) {
      for (i++; i < lines.length && !/^\}/.test(lines[i]); i++) {
        const f = lines[i].match(/^\s*(repeated |optional )?([\w.]+) (\w+) = \d+;/);
        if (!f) continue;
        const [, label, type, field] = f;
        let ts;
        if (scalars[type]) ts = scalars[type];
        else if (type.startsWith(ARGO)) {
          const short = type.slice(ARGO.length);
          if (!argoTypes[short]) throw new Error(`${file}: no UI type for Argo message ${short}`);
          ts = argoTypes[short];
          usedArgo.add(ts.replace(/^List<(\w+)>$/, "$1"));
          if (ts.startsWith("List<")) usedArgo.add("List");
        } else if (type.startsWith("google.protobuf.")) throw new Error(`${file}: unsupported field type ${type}`);
        else ts = type;
        fields.push({ name: field, ts: label === "repeated " ? `${ts}[]` : ts, doc: docAbove(lines, i) });
      }
    }
    if (messages.has(name)) throw new Error(`message ${name} is declared twice`);
    messages.set(name, { file, doc, fields });
  }
}

const out = [
  "/* Generated by scripts/gen-api-types.mjs from server/api/v1/*.proto. Do not edit. */",
  "",
  `import type { ${[...usedArgo].sort().join(", ")} } from "../types";`,
  "",
];
for (const [name, { file, doc, fields }] of [...messages].sort(([a], [b]) => a.localeCompare(b))) {
  out.push(`/** ${doc ? `${doc} ` : ""}(${file}) */`);
  if (!fields.length) {
    out.push(`export type ${name} = Record<string, never>;`, "");
    continue;
  }
  out.push(`export interface ${name} {`);
  for (const f of fields) {
    if (f.doc) out.push(`  /** ${f.doc} */`);
    out.push(`  ${f.name}?: ${f.ts};`);
  }
  out.push("}", "");
}
writeFileSync(outFile, out.join("\n"));
console.log(`wrote ${messages.size} messages to ${path.relative(process.cwd(), outFile)}`);
