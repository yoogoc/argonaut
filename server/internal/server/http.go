// Login and first-run setup are available before a session exists.
var skipAuthOperations = []string{
	v1.OperationOauth2ServiceRedirect,
	v1.OperationOauth2ServiceCallback,
	v1.OperationAuthzServiceSetupStatus,
	v1.OperationAuthzServiceSetupAdmin,
}

// NewHTTPServer builds the HTTP server. This is the only transport: the UI talks HTTP, and streaming
// endpoints are Server-Sent Events generated by Kratos from the proto `stream` declarations.
func NewHTTPServer(
	c *conf.Server,
	sso *conf.SSO,
	authzConf *conf.Authz,
	signer *xoidc.Signer,
	logger *slog.Logger,
	oauth2 *service.Oauth2Service,
	archived *service.ArchivedWorkflowService,
	authzUC *biz.AuthzUsecase,
	workflow *service.WorkflowService,
	template *service.WorkflowTemplateService,
	clusterTemplate *service.ClusterWorkflowTemplateService,
	cron *service.CronWorkflowService,
	authz *service.AuthzService,
	info *service.InfoService,
	artifacts *service.ArtifactHandler,
	clusters *service.ClusterService,
	sw *pkgargo.ClusterSwitch,
) *http.Server {
	mws := []middleware.Middleware{
		recovery.Recovery(),
		logging.Server(logger),
		km.ProtoValidate(),
		pinCluster(sw),
	}
	needsAuth := func(_ context.Context, operation string) bool {
		for _, skip := range skipAuthOperations {
			if skip == operation {
				return false
			}
		}
		return true
	}
	devSubject := conf.DevelopmentSubject(sso, authzConf)
	if devSubject == "" {
		mws = append(mws, selector.Server(xoidc.Auth(signer)).Match(needsAuth).Build())
	} else {
		logger.Warn("single sign-on is disabled: every request uses the development identity and can read and modify workflow data without grants",
			"devSubject", devSubject)
		mws = append(mws, xoidc.DevAuth(devSubject))
	}

	// Runs after authentication so super admins can be recognised and exempted (DESIGN §4.2).
	mws = append(mws, selector.Server(authzFresh(authzUC)).Match(needsAuth).Build())

	opts := []http.ServerOption{
		http.Middleware(mws...),
		http.ResponseEncoder(responseEncoder),
		http.Filter(handlers.CORS(
			handlers.AllowedHeaders([]string{"X-Requested-With", "Content-Type", "Authorization", service.RevisionHeader}),
			handlers.ExposedHeaders([]string{service.RevisionHeader, service.ClusterHeader}),
			handlers.AllowedMethods([]string{"GET", "POST", "PUT", "HEAD", "OPTIONS", "DELETE", "PATCH"}),
			handlers.AllowedOrigins([]string{"*"}),
		)),
	}
	if c.GetHttp().GetNetwork() != "" {
		opts = append(opts, http.Network(c.GetHttp().GetNetwork()))
	}
	addr := c.GetHttp().GetAddr()
	if addr == "" {
		addr = "0.0.0.0:4100"
		if devSubject != "" {
			addr = "127.0.0.1:4100"
		}
	}
	opts = append(opts, http.Address(addr))
	if c.GetHttp().GetTimeout() != nil {
		// Streaming endpoints must not be cut off by the unary timeout; Kratos applies this per
		// request, and SSE handlers manage their own lifetime through the request context.
		opts = append(opts, http.Timeout(c.GetHttp().GetTimeout().AsDuration()))
	}

	srv := http.NewServer(opts...)

	srv.HandleFunc("/health", func(w stdhttp.ResponseWriter, _ *stdhttp.Request) {
		w.WriteHeader(stdhttp.StatusOK)
		_, _ = w.Write([]byte("OK"))
	})

	v1.RegisterOauth2ServiceHTTPServer(srv, oauth2)
	v1.RegisterWorkflowServiceHTTPServer(srv, workflow)
	v1.RegisterArchivedWorkflowServiceHTTPServer(srv, archived)
	v1.RegisterWorkflowTemplateServiceHTTPServer(srv, template)
	v1.RegisterClusterWorkflowTemplateServiceHTTPServer(srv, clusterTemplate)
	v1.RegisterCronWorkflowServiceHTTPServer(srv, cron)
	v1.RegisterAuthzServiceHTTPServer(srv, authz)
	v1.RegisterInfoServiceHTTPServer(srv, info)
	v1.RegisterClusterServiceHTTPServer(srv, clusters)

	// Artifact downloads bypass the Kratos codec so the payload can stream. The generated routes
	// above use fixed paths, so these prefixes cannot collide with them.
	registerArtifactRoutes(srv, devSubject, signer, authzUC, artifacts, sw)

	// Everything else is the UI. Registered last so the API routes above always win.
	srv.HandlePrefix("/", web.Handler())

	return srv
}

// registerArtifactRoutes mounts the streaming download handlers. They sit outside the Kratos
// middleware chain, so the same authentication the RPCs get has to be applied explicitly here —
// forgetting it would leave every artifact readable by anyone who can reach the port.
func registerArtifactRoutes(srv *http.Server, devSubject string, signer *xoidc.Signer, authzUC *biz.AuthzUsecase, artifacts *service.ArtifactHandler, sw *pkgargo.ClusterSwitch) {
	routes := map[string]stdhttp.HandlerFunc{
		"/api/v1/artifacts/":          artifacts.Output,
		"/api/v1/input-artifacts/":    artifacts.Input,
		"/api/v1/archived-artifacts/": artifacts.Archived,
	}
	for prefix, handler := range routes {
		srv.HandlePrefix(prefix, withIdentity(devSubject, signer, freshHandler(authzUC, pinClusterHandler(sw, handler))))
	}
}

// withIdentity resolves the caller the same way the middleware chain does, so these raw handlers
// authenticate identically to the RPCs.
func withIdentity(devSubject string, signer *xoidc.Signer, next stdhttp.HandlerFunc) stdhttp.HandlerFunc {
	if devSubject != "" {
		return func(w stdhttp.ResponseWriter, r *stdhttp.Request) {
			user := &viewer.UserViewer{Subject: devSubject, Name: devSubject + " (development)"}
			next(w, r.WithContext(viewer.NewUserContext(r.Context(), user)))
		}
	}
	return func(w stdhttp.ResponseWriter, r *stdhttp.Request) {
		user, err := xoidc.UserFromRequest(signer, r)
		if err != nil {
			stdhttp.Error(w, err.Error(), stdhttp.StatusUnauthorized)
			return
		}
		next(w, r.WithContext(viewer.NewUserContext(r.Context(), user)))
	}
}

// authzFresh brings this replica's authorization snapshot up to the committed revision — or to the
// newer one the client reports having seen — before the request is decided, and reports the revision
// the request was decided at (DESIGN §4.3).
func authzFresh(uc *biz.AuthzUsecase) middleware.Middleware {
	return func(handler middleware.Handler) middleware.Handler {
		return func(ctx context.Context, req any) (any, error) {
			var minRevision int64
			tr, ok := transport.FromServerContext(ctx)
			if ok {
				minRevision, _ = strconv.ParseInt(tr.RequestHeader().Get(service.RevisionHeader), 10, 64)
			}
			if err := uc.EnsureFresh(ctx, minRevision); err != nil {
				return nil, err
			}
			reply, err := handler(ctx, req)
			if ok && tr.ReplyHeader().Get(service.RevisionHeader) == "" {
				tr.ReplyHeader().Set(service.RevisionHeader, strconv.FormatInt(uc.Revision(), 10))
			}
			return reply, err
		}
	}
}

// freshHandler is authzFresh for the raw (non-Kratos) handlers.
func freshHandler(uc *biz.AuthzUsecase, next stdhttp.HandlerFunc) stdhttp.HandlerFunc {
	return func(w stdhttp.ResponseWriter, r *stdhttp.Request) {
		minRevision, _ := strconv.ParseInt(r.Header.Get(service.RevisionHeader), 10, 64)
		if err := uc.EnsureFresh(r.Context(), minRevision); err != nil {
			stdhttp.Error(w, err.Error(), stdhttp.StatusServiceUnavailable)
			return
		}
		w.Header().Set(service.RevisionHeader, strconv.FormatInt(uc.Revision(), 10))
		next(w, r)
	}
}

// pinCluster fixes the cluster a request runs against when it arrives (pkgargo.ClusterSwitch), so a
// switch in the middle of a request cannot make it read one cluster and write another. With switching
// enabled the reply names the cluster that answered.
func pinCluster(sw *pkgargo.ClusterSwitch) middleware.Middleware {
	return func(handler middleware.Handler) middleware.Handler {
		return func(ctx context.Context, req any) (any, error) {
			ctx = sw.Pin(ctx)
			if sw.Enabled() {
				if tr, ok := transport.FromServerContext(ctx); ok {
					tr.ReplyHeader().Set(service.ClusterHeader, sw.For(ctx).ID)
				}
			}
			return handler(ctx, req)
		}
	}
}

// pinClusterHandler is pinCluster for the raw (non-Kratos) handlers.
func pinClusterHandler(sw *pkgargo.ClusterSwitch, next stdhttp.HandlerFunc) stdhttp.HandlerFunc {
	return func(w stdhttp.ResponseWriter, r *stdhttp.Request) {
		ctx := sw.Pin(r.Context())
		if sw.Enabled() {
			w.Header().Set(service.ClusterHeader, sw.For(ctx).ID)
		}
		next(w, r.WithContext(ctx))
	}
}
